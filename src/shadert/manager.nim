######################################################################################################################################################################

type
  ShaderManager = object
    shaders: Table[string, CIRContext]
    interpreter: CIRContext

template addShader(sm: var ShaderManager, fn: untyped) =
  let shader = compileToIR(fn)
  let name = shader.body.args[0].args[0].name
  sm.shaders[name] = shader
  
